def test_dry_run_writes_nothing():
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        f = _layout(tmp)
        before = _bytes(f)
        r = _run(tmp, "--dry-run")
        assert r.returncode == 0 and "DRY RUN — 3 file(s)" in r.stdout, (r.stdout, r.stderr)
        assert _bytes(f) == before and not list(tmp.glob("*.tar.gz")) and not list(tmp.glob("*.jsonl"))


def test_real_run_renders_same_bytes_as_old_code():
    import ada_prepare
    import journal_web
    import monitor_9router as tr
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        f = _layout(tmp)
        before = _bytes(f)
        r = _run(tmp)
        assert r.returncode == 0, (r.stdout, r.stderr)
        assert f["md"].read_bytes() == before["md"], ".md must not be touched"
        (backup,) = tmp.glob("low239_9router_journal_backup_*.tar.gz")
        json_keys = sorted(k for k in f if k != "md")
        with tarfile.open(backup) as tar:
            assert sorted(tar.getnames()) == sorted(str(f[k].relative_to(tmp)) for k in json_keys)
            assert tar.extractfile(str(f["9router_2026-09-15"].relative_to(tmp))).read() == before["9router_2026-09-15"]
        (journal,) = tmp.glob("low239_9router_journal_*.journal.jsonl")
        rows = {x["file"]: x for x in (json.loads(y) for y in journal.read_text(encoding="utf-8").splitlines())}
        assert set(rows) == {str(f[k]) for k in json_keys}, rows
        assert rows[str(f["9router_2026-09-13"])]["to_keys"] == ["date", "read_error"]

        journal_dir = f["9router_2026-09-15"].parent
        with mock.patch.object(tr, "WEB_URL", WEB_URL), mock.patch.object(tr, "JOURNAL", journal_dir):
            for p in sorted(journal_dir.glob("9router_*.json")):
                m = json.loads(p.read_text(encoding="utf-8"))
                assert "ngay" not in m and "loi_doc" not in m, m
                d = m["date"]
                assert tr.write_md(m) == (EXPECTED / f"{d}.md").read_text(encoding="utf-8"), d
                assert tr.still_for(m) == json.loads((EXPECTED / f"{d}.still_for.json").read_text(encoding="utf-8")), d
                assert tr.summary_tele(m) == (EXPECTED / f"{d}.tele.txt").read_text(encoding="utf-8"), d
            assert journal_web.page_list_clean() == (EXPECTED / "list.html").read_bytes()

            # Ada reads the new keys, its own dump keeps the old keys (LOW-243)
            files = iter(sorted(journal_dir.glob("9router_*.json")))

            class _Fixed(_datetime):
                @classmethod
                def now(cls, tz=None):
                    return _datetime(2026, 9, 15, 8, 0, tzinfo=tz)
            with mock.patch.object(tr, "download", lambda d, lam_moi=False: json.loads(next(files).read_text(encoding="utf-8"))), \
                    mock.patch.object(ada_prepare, "datetime", _Fixed):
                got = ada_prepare.gather_9router(2)
            assert got == json.loads((EXPECTED / "ada_gather_9router.json").read_text(encoding="utf-8")), got


def test_bad_shape_or_conflict_refuses_everything():
    cases = (({"ngay": "d", "date": "d"}, "both"),
             (["ngay"], "not an object"),
             ({"date": "d", "tong_moi": {}}, "unknown key 'tong_moi'"),
             ({"date": "d", "tong": {"req": 1, "loi": 0, "error_count": 0}}, "both"),
             ({"date": "d", "tong": {"req": 1, "la": 0}}, "unknown key 'la'"),
             ({"date": "d", "tong": []}, "expected dict"),
             ({"date": "d", "theo_model": {"m @ c": {"req": 1, "phien": 2}}}, "unknown key 'phien'"),
             ({"date": "d", "theo_model": {"m @ c": 3}}, "expected dict"),
             ({"date": "d", "top_prompt": {"luc": "x"}}, "expected list"),
             ({"date": "d", "top_prompt": [{"luc": "x", "gio": "y"}]}, "unknown key 'gio'"),
             ({"date": "d", "loi_ket_noi": [{"ten": "c", "name": "c"}]}, "both"),
             ({"date": "d", "loi_ket_noi": ["c"]}, "expected dict"),
             ({"date": "d", "cache_kem": [{"model": "m", "vai": [], "vai_tro": []}]}, "unknown key 'vai_tro'"),
             ({"date": "d", "ket_noi": {"co_watcher": True, "ip": {"1.2.3.4": {"ket_noi": 1}}}}, "legacy_connection.ip"),
             ({"date": "d", "ket_noi": {"co_watcher": False, "ip": {}, "them": 1}}, "unknown key 'them'"),
             ({"date": "d", "vai": {"theo_vai": {"blog/x": {"phien": 1, "sessions": 1}}}}, "both"),
             ({"date": "d", "vai": {"theo_brand": {"blog": {"bai": 1, "so_bai": 1}}}}, "unknown key 'so_bai'"),
             ({"date": "d", "vai": {"tong": 1}}, "unknown key 'tong'"),
             ({"date": "d", "vai": []}, "expected dict"),
             ({"date": "d", "lat_model": []}, "expected dict"),
             ({"date": "d", "loi_doc": ["x"]}, "expected str"))
    for bad, word in cases:
        with tempfile.TemporaryDirectory() as t:
            tmp = Path(t)
            f = _layout(tmp, {"9router_2026-09-01.json": bad})
            before = _bytes(f)
            r = _run(tmp)
            assert r.returncode == 1 and word in r.stderr and "nothing written" in r.stderr, (bad, r.stderr)
            assert _bytes(f) == before and not list(tmp.glob("*.tar.gz")), bad


def test_rerun_is_noop():
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        f = _layout(tmp, {"9router_2026-09-01.json": {"ngay": "2026-09-01", "ket_noi": {"co_watcher": False, "ip": {}}}})
        assert _run(tmp).returncode == 0
        assert json.loads(f["9router_2026-09-01.json"].read_text(encoding="utf-8")) == {
            "date": "2026-09-01", "legacy_connection": {"has_watcher": False, "ip": {}}}
        after = _bytes(f)
        r = _run(tmp)
        assert r.returncode == 0 and "nothing to do" in r.stdout, r.stdout
        assert _bytes(f) == after and len(list(tmp.glob("*.tar.gz"))) == 1


