def _clean(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def _layout(tmp: Path, extra=None) -> dict:
    """Copy the old fixtures (+ their .md) into tmp/state/9router/journal/."""
    j = tmp / "state" / "9router" / sp.JOURNAL_DIR
    j.mkdir(parents=True)
    files = {}
    for p in sorted(OLD_DIR.glob("9router_*.json")):
        shutil.copy(p, j / p.name)
        files[p.stem] = j / p.name
    (j / "9router_2026-09-15.md").write_text("md is not touched\n", encoding="utf-8")
    files["md"] = j / "9router_2026-09-15.md"
    for name, data in (extra or {}).items():
        (j / name).write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
        files[name] = j / name
    return files


def _run(tmp: Path, *extra):
    return subprocess.run([sys.executable, str(ROOT / "migrate_9router_journal.py"), "--state", str(tmp / "state"),
                           *extra], capture_output=True, text=True, cwd=ROOT)


def _bytes(files: dict) -> dict:
    return {k: p.read_bytes() for k, p in files.items()}


