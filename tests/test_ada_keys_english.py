def _pairs(old, new, path="", out=None):
    """Walk old and new dumps in parallel: same values under the same or renamed keys.
    Keys present in both pair BY NAME (data keys: roles, statuses, models); only the
    leftover (renamed) keys pair by position, which the code's dict literals fix.
    -> {(path of the parent, old key, new key)} for every renamed key."""
    out = set() if out is None else out
    if isinstance(old, dict):
        assert isinstance(new, dict) and len(old) == len(new), (path, list(old), new)
        only_old = [k for k in old if k not in new]
        only_new = [k for k in new if k not in old]
        pairs = [(k, k) for k in old if k in new] + list(zip(only_old, only_new))
        for ko, kn in pairs:
            if ko != kn:
                out.add((path, ko, kn))
            _pairs(old[ko], new[kn], f"{path}.{kn}" if path else kn, out)
    elif isinstance(old, list):
        assert isinstance(new, list) and len(old) == len(new), (path, old, new)
        for vo, vn in zip(old, new):
            _pairs(vo, vn, path + "[]", out)
    else:
        assert old == new, (path, old, new)
    return out


def _generic(path: str) -> str:
    """Dump path -> table section name (profile/model/brand/date keys become `*`)."""
    parts = path.split(".") if path else []
    out = []
    for p in parts:
        prev = out[-1] if out else ""
        if prev in ("by_role", "cost_by_role", "brand", "by_score_tier", "by_source", "by_category",
                    "router_cost_by_model", "by_status", "avg_seconds"):
            out.append("*")
        elif p in ("high_score_dropped[]", "low_score_picked[]"):
            out.append("items[]")
        else:
            out.append(p)
    return ".".join(["ada_metrics"] + out)


def _run_submit(asub, wd: Path, state: Path, spec: dict, *argv):
    (wd / "spec.json").write_text(json.dumps(spec, ensure_ascii=False), encoding="utf-8")
    import ada_prepare
    import env_load
    buf = io.StringIO()
    with mock.patch.object(env_load, "state_dir", lambda: state), \
            mock.patch.object(ada_prepare, "datetime", _Fixed), \
            mock.patch.object(asub, "datetime", _Fixed), \
            mock.patch.object(sys, "argv", ["ada_submit.py", *argv]), redirect_stdout(buf):
        try:
            rc = asub.main()
        except SystemExit as e:
            rc = e.code
    return rc, buf.getvalue()


