def run_prepare(ap, tmp: Path, ngay: int = 2):
    """Run `ap.main()` (old or new ada_prepare) on the fixture. -> (dump, brief, wd)."""
    import env_load
    import hermes_adapter
    import monitor_9router
    state, drafts, home = tmp / "state", tmp / "drafts", tmp / "hermes"
    for d in (state, drafts, home):
        d.mkdir(parents=True, exist_ok=True)
    _candidates(state)
    _drafts(drafts)
    journals = _journals()
    profiles = [home / "profiles" / n / "state.db" for n in SESSIONS]
    real_glob = Path.glob
    with ExitStack() as st:
        # readdir order differs by filesystem (APFS vs ext4 on CI): ada_prepare builds
        # `draft.by_status` (and the brief/report line) in glob order, so the fixture sorts it.
        st.enter_context(mock.patch.object(Path, "glob", lambda self, pat, *a, **k:
                                           iter(sorted(real_glob(self, pat, *a, **k)))))
        st.enter_context(mock.patch.object(env_load, "state_dir", lambda: state))
        st.enter_context(mock.patch.object(ap, "DRAFTS", drafts))
        st.enter_context(mock.patch.object(ap, "HERMES", home))
        st.enter_context(mock.patch.object(ap, "datetime", _Fixed))
        st.enter_context(mock.patch.object(hermes_adapter, "job", lambda tu_ts=None, **k: [dict(j) for j in JOBS]))
        st.enter_context(mock.patch.object(hermes_adapter, "state_db_each_profile", lambda h: list(profiles)))
        st.enter_context(mock.patch.object(hermes_adapter, "summary_session",
                                           lambda p, moc: SESSIONS[p.parent.name]))
        st.enter_context(mock.patch.object(monitor_9router, "download",
                                           lambda d, lam_moi=False: json.loads(json.dumps(journals[d]))
                                           if d in journals else None))
        st.enter_context(mock.patch.dict(os.environ, {"CT_BRAND": "blog"}))
        st.enter_context(mock.patch.object(sys, "argv", ["ada_prepare.py", "--ngay", str(ngay), "--im"]))
        assert ap.main() == 0
        wd = ap.workdir()
    (dump_file,) = [p for p in wd.glob("*.json")]
    dump = json.loads(dump_file.read_text(encoding="utf-8"))
    brief = (wd / "brief.md").read_text(encoding="utf-8")
    brief = brief.replace(str(wd), "<WD>").replace(str(ap.ROOT), "<ROOT>")
    return dump, brief, wd, dump_file.name


