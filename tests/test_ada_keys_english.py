def test_metrics_dump_same_values_under_table_keys():
    import ada_prepare
    import state_paths
    old = json.loads((GOLDEN / "metrics_old.json").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as t:
        new, _, wd, name = run_prepare(ada_prepare, Path(t))
    assert name == state_paths.ADA_METRICS_FILE == TABLE["files"]["manifest.json"], name
    renamed = _pairs(old, new)
    assert renamed, "golden dump must differ in keys"
    missing = sorted((p, o, n) for p, o, n in renamed if TABLE.get(_generic(p), {}).get(o) != n)
    assert not missing, f"renamed key not in ada_keys_v2.json (section, old, new): {missing}"
    root = {k: v for k, v in TABLE["ada_metrics"].items() if not k.startswith("_")}
    assert list(new) == ["days", "brand", "candidates", "draft", "kanban", "token"] and \
        {("", o, n) for o, n in root.items()} <= renamed, list(new)
    # every table row of the dump is exercised by the fixture (a table row nobody writes is a typo)
    rows = {(sec, o, n) for sec, m in TABLE.items() if sec.startswith("ada_metrics")
            for o, n in m.items() if not o.startswith("_") and sec != "ada_metrics.token.router_journal_in_memory"}
    seen = {(_generic(p), o, n) for p, o, n in renamed}
    assert rows == seen, (sorted(rows - seen), sorted(seen - rows))


def test_brief_identical_except_spec_template_tokens():
    import ada_prepare
    golden = (GOLDEN / "brief.md").read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as t:
        _, brief, _, _ = run_prepare(ada_prepare, Path(t))
    head, tail = golden.split(SPEC_HEADING)
    for o, n in BRIEF_TOKENS:
        assert o in tail, o
        tail = tail.replace(o, n)
    assert brief == head + SPEC_HEADING + tail, brief
    assert all(o not in brief for o, _ in BRIEF_TOKENS)
    # the JSON template is the table's spec keys, in order
    spec = json.loads(brief.split(SPEC_HEADING)[1].split("\n", 1)[1].rsplit("\nKhông có gì", 1)[0])
    assert list(spec) == ["observations", "rubric_proposals", "token", "router", "conclusion"], spec
    assert list(spec["rubric_proposals"][0]) == ["change", "evidence"]


def test_report_identical_for_old_and_new_spec_keys():
    import ada_prepare
    import ada_submit as asub
    with tempfile.TemporaryDirectory() as t:
        m, _, _, _ = run_prepare(ada_prepare, Path(t))
    for old, new, gold in ((OLD_SPEC, NEW_SPEC, "report.txt"), (OLD_SPEC_EMPTY, NEW_SPEC_EMPTY, "report_no_proposals.txt")):
        want = (GOLDEN / gold).read_text(encoding="utf-8")
